def build_ui_text(language_code: str | None) -> dict[str, str]:
    lang = normalize_ui_language(language_code)
    base = deepcopy(UI_TEXTS[DEFAULT_UI_LANGUAGE])
    base.update(UI_TEXTS.get(lang, {}))
    return base
