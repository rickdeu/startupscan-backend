DEFAULT_UI_LANGUAGE = "pt"

SUPPORTED_UI_LANGUAGES = [
    ("pt", "Portugues"),
    ("en", "English"),
    ("ru", "Russkiy"),
    ("de", "Deutsch"),
    ("es", "Espanol"),
    ("zh-hans", "JianTi ZhongWen"),
    ("umb", "Umbundu"),
]

SUPPORTED_UI_LANGUAGE_CODES = {code for code, _ in SUPPORTED_UI_LANGUAGES}


def normalize_ui_language(value: str | None) -> str:
    code = str(value or "").strip().lower().replace("_", "-")
    if code.startswith("zh"):
        code = "zh-hans"
    if code in SUPPORTED_UI_LANGUAGE_CODES:
        return code
    return DEFAULT_UI_LANGUAGE


def to_django_language(ui_language: str | None) -> str:
    code = normalize_ui_language(ui_language)
    # Umbundu ainda nao tem locale Django no projeto; usa fallback funcional.
    if code == "umb":
        return "pt"
    return code


